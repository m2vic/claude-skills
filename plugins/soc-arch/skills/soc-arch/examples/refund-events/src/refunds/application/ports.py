"""What the application needs from outside. Receiving from a queue is not here:
receiving drives the application, so it is an inbound adapter."""
from typing import ContextManager, Optional, Protocol

from refunds.domain.refund import Refund, RefundSucceeded


class Transaction(Protocol):
    def get_refund(self, refund_id: str) -> Optional[Refund]: ...
    def save_refund(self, refund: Refund) -> None: ...
    def add_to_outbox(self, event: RefundSucceeded) -> None: ...
    def was_handled(self, key: str) -> bool: ...
    def mark_handled(self, key: str) -> None: ...


class Database(Protocol):
    def transaction(self) -> ContextManager[Transaction]: ...
    def pending_events(self, limit: int) -> list[RefundSucceeded]: ...
    def mark_published(self, event_id: str) -> None: ...


class EventPublisher(Protocol):
    def publish(self, event: RefundSucceeded) -> None: ...


class CustomerMailer(Protocol):
    def refund_succeeded(self, to: str, refund_id: str) -> None: ...
